#!/usr/bin/env python3
"""Winding and Mirrored, cover figure (second frame). Native Blender scene in the graphite/cyan visual system.

Theorem W11: z(t) = tanh(c t / 2), c = a + ib, and (1 + z)/(1 - z) = exp(c t). Write L = log((1 + z)/(1 - z)),
so that z = tanh(L / 2). L lives on a cylinder: Re L runs from -infinity (the pole -1) to +infinity (the pole +1)
and Im L is an angle of period 2 pi. Row 0 is the curve of W11 at the equal steps t_j = j d: L = c t_j.
Row m is the same curve turned about the two poles by the angle phi_m = 2 pi m / M: L = c t_j + i phi_m,
that is (1 + z)/(1 - z) = exp(i phi_m) exp(c t_j). With c = 1/3 + i, d = pi/20 and M = 12 the row offset is
i pi/6 = (3 + i) c d, so the rows together are the square lattice c d Z[i]: every dot is tanh(c d g / 2) for a
Gaussian integer g = p + iq, with g and g + (36 + 12i) giving the same dot.

Re L = a t_j depends on j only. The disc about +1 is Re L >= x0, the inside of the circle of Apollonius on which
the distances to the poles are in the ratio exp(x0); the disc about -1 is its mirror. x0 = pi/3 = a pi is the
value of Re L where row 0 completes its first half-turn (j = 20). The dots drawn are
  every lattice point with 20 <= |j| <= J_END (all twelve rows), the two discs, and
  the points of row 0 with |j| <= 19, the S between them.
A dot is a disc of radius KAPPA |dz/dL| |c| d about its point: KAPPA times the local lattice step.

Every fact the image draws is asserted before anything renders, and the facts and the dot list are written
to evidence.json beside this file. Nothing typed appears in the image.

Run:  blender -b --factory-startup -P build_scene.py -- [WIDTH HEIGHT OUTPUT.png [key=value ...]]
      defaults: 3840 2705 ../figures/00-cover-4k.png (relative to this file)
      keys (tests only; the defaults are the published figure):
        border=x0,x1,y0,y1  samples=64  save=0|1  c0=r,g,b,strength  c1=r,g,b,strength
      The mathematics (sections 1 to 3) also runs without Blender: python3 build_scene.py
      (evidence.json is rewritten by every run; its data hash is that of Blender 5.2.3's Python)
Author: lmtlssss🜐.
"""
import cmath, hashlib, json, math, sys, time
from fractions import Fraction as F
from pathlib import Path

ROOT = Path(__file__).resolve().parent
ARGV = sys.argv[sys.argv.index('--') + 1:] if '--' in sys.argv else []
WIDTH = int(ARGV[0]) if len(ARGV) > 0 else 3840
HEIGHT = int(ARGV[1]) if len(ARGV) > 1 else 2705
OUTPUT = ROOT / (ARGV[2] if len(ARGV) > 2 else '../figures/00-cover-4k.png')
OPT = dict(x.split('=', 1) for x in ARGV[3:])

# ---------------------------------------------------------------------------------------------
# 1. The lattice (no Blender needed)
# ---------------------------------------------------------------------------------------------
A_EXACT, B_EXACT = F(1, 3), F(1)        # c = a + ib = 1/3 + i
D_OVER_PI = F(1, 20)                    # d = pi/20: forty steps to one turn of the angle b t
M = 12                                  # rows: phi_m = 2 pi m / 12
J_RIM = 20                              # x0 = a * J_RIM * d = pi/3: the rims are the dots with |j| = 20
J_END = 96                              # rows stop at |j| = 96, where a dot is about half a 4K pixel
KAPPA = 0.33                            # dot radius = KAPPA |dz/dL| |c| d

a, b = float(A_EXACT), float(B_EXACT)
c = complex(a, b)
d = math.pi * float(D_OVER_PI)
X0 = a * J_RIM * d

facts = []
def fact(fid, statement, cases, **numbers):
    facts.append({'id': fid, 'statement': statement, 'cases_checked': cases, 'result': True,
                  'numbers': numbers})
    print('ASSERTED', fid, '-', statement, '(%d cases)' % cases,
          ' '.join('%s=%s' % kv for kv in numbers.items()), flush=True)

# The row offset is (3 + i) c d, exactly: (3 + i)(1/3 + i) = (10/3) i and (10/3) * (1/20) = 1/6 = 2/M.
re_ = 3 * A_EXACT - 1 * B_EXACT
im_ = 3 * B_EXACT + 1 * A_EXACT
assert re_ == 0 and im_ * D_OVER_PI == F(2, M)
# Then the lattice {j c d + m 2 pi i / M} is generated by c d and (3 + i) c d - 3 c d = i c d: a square lattice.
# The period 2 pi i is (36 + 12 i) c d: (36 + 12i)(1/3 + i) = 40 i and 40 * (1/20) = 2.
pr, pi_ = 36 * A_EXACT - 12 * B_EXACT, 36 * B_EXACT + 12 * A_EXACT
assert pr == 0 and pi_ * D_OVER_PI == 2
fact('LAT', 'the row offset 2 pi i / 12 equals (3 + i) c d and the period 2 pi i equals (36 + 12 i) c d, in exact '
     'rational arithmetic: the twelve rows form the square lattice c d Z[i] on the cylinder, step |c| d', 2,
     step_L=abs(c) * d, row_spacing_L=2 * math.pi * a / (M * abs(c)))

def in_set(j, m):
    return (J_RIM <= abs(j) <= J_END) or (m == 0 and abs(j) < J_RIM)

KEYS = [(j, m) for m in range(M) for j in range(-J_END, J_END + 1) if in_set(j, m)]
IDX = {k: i for i, k in enumerate(KEYS)}
T = {k: k[0] * d for k in KEYS}
PHI = {k: 2 * math.pi * k[1] / M for k in KEYS}
Z = {k: cmath.tanh((c * T[k] + 1j * PHI[k]) / 2) for k in KEYS}          # from the hyperbolic tangent
E = {k: cmath.exp(c * T[k]) * cmath.exp(1j * PHI[k]) for k in KEYS}      # from the exponential, separately
RATIO = {k: (1 + Z[k]) / (1 - Z[k]) for k in KEYS}
N_DISC = sum(1 for k in KEYS if abs(k[0]) >= J_RIM)
N_S = len(KEYS) - N_DISC

TOL = 1e-9
gap = min(abs(1 - Z[k]) for k in KEYS)
assert gap > 0
mob = max(abs(RATIO[k] - E[k]) / abs(E[k]) for k in KEYS)
assert mob < TOL
fact('W11b', '1 - z is not 0, and (1 + z)/(1 - z) = exp(c t_j + i phi_m) at every dot, relative error below 1e-9, '
     'z from tanh and the right side from exp', len(KEYS), min_abs_1_minus_z=gap, max_relative_error=mob)

# Row 0 is the curve of W11 itself: z_0 = 0, z_{-j} = -z_j, a continuous logarithm is the straight row c t_j.
row0 = [(j, 0) for j in range(-J_END, J_END + 1)]
assert Z[(0, 0)] == 0
half0 = max(abs(Z[(-j, 0)] + Z[(j, 0)]) for j in range(J_END + 1))
assert half0 <= 1e-15
Lc = []
for k in row0:
    lg = cmath.log(RATIO[k])
    if Lc:
        lg += 2j * math.pi * round((Lc[-1].imag - lg.imag) / (2 * math.pi))
    Lc.append(lg)
k0 = round(Lc[J_END].imag / (2 * math.pi))
Lc = [x - 2j * math.pi * k0 for x in Lc]
line = max(abs(x - c * T[k]) for x, k in zip(Lc, row0))
assert line < TOL
fact('W11a-row0', 'row 0 is the curve of W11: z_0 = 0, z_{-j} = -z_j, and a continuous branch of the logarithm of '
     '(1 + z_j)/(1 - z_j) equals c t_j, the straight row of equal steps', len(row0),
     max_abs_z_minus_j_plus_z_j=half0, max_abs_log_minus_ct=line)

# Each step along a row multiplies |(1 + z)/(1 - z)| by exp(a d); |(1 + z)/(1 - z)| = exp(a t_j) for every row.
ead = math.exp(a * d)
modc = max(abs(abs(RATIO[k]) - math.exp(a * T[k])) / math.exp(a * T[k]) for k in KEYS)
assert modc < TOL
steps = [(k, (k[0] + 1, k[1])) for k in KEYS if (k[0] + 1, k[1]) in IDX]
step = max(abs(abs(RATIO[k2]) / abs(RATIO[k1]) - ead) / ead for k1, k2 in steps)
assert step < TOL
fact('W11cd', '|(1 + z)/(1 - z)| = exp(a t_j) at every dot, and each step along a row multiplies it by exp(a d)',
     len(steps), exp_a_d=ead, max_relative_error_modulus=modc, max_relative_error_step=step)

tJ = J_END * d
bound = 2 / (math.exp(a * tJ) - 1)
endp, endm = abs(Z[(J_END, 0)] - 1), abs(Z[(-J_END, 0)] + 1)
assert endp <= bound and endm <= bound
fact('W11e', '|z_J - 1| <= 2/(exp(a t_J) - 1) at the last dot of row 0, and |z_{-J} + 1| the same at the first', 2,
     J=J_END, t_J=tJ, abs_zJ_minus_1=endp, abs_z_minusJ_plus_1=endm, bound=bound)

# The discs and the S.
logr = {k: math.log(abs(RATIO[k])) for k in KEYS}                        # Re L, from z
rim = [k for k in KEYS if abs(k[0]) == J_RIM]
rim_err = max(abs(abs(RATIO[k]) ** (1 if k[0] > 0 else -1) - math.exp(X0)) / math.exp(X0) for k in rim)
assert rim_err < TOL and len(rim) == 2 * M
assert all(abs(logr[k]) >= X0 * (1 - 1e-12) for k in KEYS if abs(k[0]) >= J_RIM)
assert all(abs(logr[k]) < X0 for k in KEYS if abs(k[0]) < J_RIM)
assert all(k[1] == 0 for k in KEYS if abs(logr[k]) < X0 * (1 - 1e-12))
fact('DISC', 'every dot of a disc has |Re L| >= x0 = pi/3, every dot with |Re L| < x0 is on row 0 (the S), and the '
     'outermost ring (|j| = 20, all twelve rows) lies on the circle of Apollonius of ratio exp(x0) within 1e-9',
     len(KEYS), x0=X0, exp_x0=math.exp(X0), rim_dots=len(rim), max_relative_error_rim=rim_err,
     disc_dots=N_DISC, S_dots=N_S)

# ---------------------------------------------------------------------------------------------
# 2. The drawing: dots, frame and poles
# ---------------------------------------------------------------------------------------------
ROT = 1j * c.conjugate() / abs(c)               # row 0 crosses the centre vertically (z'(0) = c/2)
ORTHO = 5.4                                     # frame width in scene units; the frame is centred on z = 0
PX = ORTHO / 3840
FRAME_H = ORTHO * 2705 / 3840
STEP = abs(c) * d
P = {k: ROT * Z[k] for k in KEYS}
R = {k: KAPPA * STEP * abs(1 - Z[k] * Z[k]) / 2 for k in KEYS}            # |dz/dL| = |1 - z^2| / 2
POLES = [ROT * -1, ROT * 1]
POLE_D = 6.0 * PX                               # half-diagonal of the gold diamond at each pole

def mirror(k):
    return (-k[0], (-k[1]) % M)

hmax, rdev = 0.0, 0.0
for k in KEYS:
    km = mirror(k)
    assert km in IDX
    hmax = max(hmax, abs(Z[km] + Z[k]))
    rdev = max(rdev, abs(R[km] - R[k]) / R[k])
assert hmax <= 1e-12 and rdev <= 1e-12
fact('HALF', 'the half-turn carries the dot set onto itself: dot (j, m) and dot (-j, -m mod 12) are both drawn, '
     'at -z of each other, with the same radius (matched by index; phi = 2 pi - phi_m and tanh has period i pi)',
     len(KEYS), max_abs_z_plus_mirror=hmax, max_relative_radius_difference=rdev)

rmin, rmax = min(R.values()) / PX, max(R.values()) / PX
assert rmin >= 0.5
fact('D1', 'dot (j, m) is the disc of radius KAPPA |c| d |1 - z^2| / 2 about z: KAPPA times the local lattice step; '
     'every dot is at least half a 4K pixel in radius', len(KEYS), KAPPA=KAPPA,
     min_radius_4k_px=rmin, max_radius_4k_px=rmax)

# No two dots touch: sweep in x, comparing only dots whose x ranges can meet.
order = sorted(KEYS, key=lambda k: P[k].real)
RM = max(R.values())
mingap, pairs = float('inf'), 0
for i, k in enumerate(order):
    x, r = P[k].real, R[k]
    for k2 in order[i + 1:]:
        if P[k2].real - x > r + RM:
            break
        pairs += 1
        g = abs(P[k2] - P[k]) - r - R[k2]
        if g < mingap:
            mingap = g
assert mingap > 0
fact('D2', 'no two dots touch or overlap (all pairs whose x ranges can meet, by a sweep in x)', pairs,
     min_gap_4k_px=mingap / PX)

mx = min(ORTHO / 2 - (abs(P[k].real) + R[k]) for k in KEYS) / PX
my = min(FRAME_H / 2 - (abs(P[k].imag) + R[k]) for k in KEYS) / PX
assert mx > 0 and my > 0
fact('D3', 'every dot lies inside the frame, which is centred on z = 0', len(KEYS),
     margin_x_4k_px=mx, margin_y_4k_px=my)

clear = min(abs(P[k] - q) - R[k] for k in KEYS for q in POLES) / PX
assert clear > POLE_D / PX
fact('D4', 'the gold diamonds at the poles -1 and +1 touch no dot', 2 * len(KEYS),
     pole_half_diagonal_4k_px=POLE_D / PX, nearest_dot_edge_to_a_pole_4k_px=clear)

def _rgbs(key, default):
    v = [float(x) for x in OPT.get(key, default).split(',')]
    return tuple(x * v[3] for x in v[:3])
COL_S = _rgbs('c0', '.84,.90,.93,.80')          # house white (foreground) at strength .80, at the centre
COL_POLE = _rgbs('c1', '.18,.44,.49,1.0')       # house thread cyan at strength 1, into the poles
def dot_colour(k):
    s = abs(k[0]) / J_END                       # linear in |Re L| = a |t_j|
    return tuple((1 - s) * x + s * y for x, y in zip(COL_S, COL_POLE))

# ---------------------------------------------------------------------------------------------
# 3. Evidence
# ---------------------------------------------------------------------------------------------
def cx(z):
    return [repr(z.real), repr(z.imag)]

data = {
    'curve': 'z = tanh(L / 2), L = c t_j + i phi_m, c = a + ib, t_j = j d, phi_m = 2 pi m / M',
    'a': str(A_EXACT), 'b': str(B_EXACT), 'd': 'pi/20', 'd_float': repr(d), 'M': M,
    'lattice': 'c d Z[i]: dot = tanh(c d g / 2), g = p + i q, g ~ g + (36 + 12 i); row m, step j <-> g = j + m (3 + i)',
    'x0': 'pi/3 = a * 20 * d', 'x0_float': repr(X0), 'J_RIM': J_RIM, 'J_END': J_END,
    'dot_set': '{(j, m): 20 <= |j| <= 96, m = 0..11} union {(j, 0): |j| <= 19}',
    'counts': {'dots': len(KEYS), 'disc_dots': N_DISC, 'S_dots': N_S, 'rows_M': M, 'rim_dots': len(rim)},
    'dot_radius_rule': 'r = KAPPA |c| d |1 - z^2| / 2', 'KAPPA': repr(KAPPA),
    'radius_4k_px': {'min': repr(rmin), 'max': repr(rmax)},
    'plane_rotation': 'P = i conj(c)/|c| z (row 0 crosses the centre vertically)',
    'frame_width_units': repr(ORTHO), 'frame_height_units': repr(FRAME_H),
    'poles_in_plane': [cx(p) for p in POLES],
    'pole_diamond_half_diagonal_4k_px': repr(POLE_D / PX),
    'dot_colour_rule': 'linear emission colour, (1 - |j|/96) * c0 + (|j|/96) * c1',
    'dot_colour_c0': [repr(x) for x in COL_S], 'dot_colour_c1': [repr(x) for x in COL_POLE],
    'ground_emission': ['0.00399', '0.0065', '0.0098'], 'look': 'EEVEE, Standard, Medium High Contrast',
    'dots': [[k[0], k[1]] + cx(Z[k]) + [repr(R[k])] for k in KEYS],
    'dots_columns': ['j', 'm', 'Re z', 'Im z', 'radius'],
}
blob = json.dumps(data, sort_keys=True, separators=(',', ':')).encode()
evidence = {
    'schema': 'mathematics.figure.evidence.v1',
    'figure': 'Winding and Mirrored, cover: the curve of W11 turned about its poles into twelve rows, '
              'cut at two circles of Apollonius, joined by row 0',
    'author': 'lmtlssss🜐',
    'generator': 'visual/build_scene.py (Python cmath and fractions, IEEE double precision)',
    'theorem': 'W11',
    'facts': facts,
    'data_sha256': hashlib.sha256(blob).hexdigest(),
    'data': data,
}
(ROOT / 'evidence.json').write_text(json.dumps(evidence, indent=1, ensure_ascii=False) + '\n', encoding='utf-8')
print('EVIDENCE evidence.json', len(facts), 'facts', len(KEYS), 'dots', flush=True)

# ---------------------------------------------------------------------------------------------
# 4. Scene (only under Blender)
# ---------------------------------------------------------------------------------------------
try:
    import bpy
except ImportError:
    sys.exit(0)

bpy.ops.wm.read_factory_settings(use_empty=True)
scene = bpy.context.scene
for engine in ('BLENDER_EEVEE', 'BLENDER_EEVEE_NEXT'):
    try:
        scene.render.engine = engine
        break
    except Exception:
        pass
scene.render.resolution_x = WIDTH
scene.render.resolution_y = HEIGHT
scene.render.resolution_percentage = 100
scene.render.image_settings.file_format = 'PNG'
scene.render.image_settings.color_mode = 'RGB'
scene.render.image_settings.color_depth = '8'
scene.render.filepath = str(OUTPUT)
scene.render.film_transparent = False
# No render metadata in the PNG (Blender's default stamp fields include the .blend path and the date).
for attr in dir(scene.render):
    if attr.startswith('use_stamp'):
        try:
            setattr(scene.render, attr, False)
        except Exception:
            pass
try:
    scene.eevee.taa_render_samples = int(OPT.get('samples', 64))
except Exception:
    pass
scene.view_settings.view_transform = 'Standard'
try:
    scene.view_settings.look = 'Medium High Contrast'
except Exception:
    pass
print('LOOK', scene.render.engine, scene.view_settings.view_transform, scene.view_settings.look, flush=True)
if 'border' in OPT:
    bx0, bx1, by0, by1 = map(float, OPT['border'].split(','))
    scene.render.use_border = True
    scene.render.use_crop_to_border = True
    scene.render.border_min_x, scene.render.border_max_x = bx0, bx1
    scene.render.border_min_y, scene.render.border_max_y = by0, by1

world = bpy.data.worlds.new('Graphite / #080d12')
scene.world = world
try:
    world.use_nodes = True
except Exception:
    pass
for node in world.node_tree.nodes:
    if node.type == 'BACKGROUND':
        node.inputs['Color'].default_value = (.0046, .0078, .0115, 1)
        node.inputs['Strength'].default_value = .5

def col(name):
    cl = bpy.data.collections.new(name)
    scene.collection.children.link(cl)
    return cl

C_ROW = col('01 / twelve rows of the W11 curve, cut at two circles of Apollonius, and row 0 between them')
C_POLES = col('02 / the poles -1 and +1')
C_STAGE = col('03 / camera and graphite ground')

def new_material(name):
    mat = bpy.data.materials.new(name)
    try:
        mat.use_nodes = True
    except Exception:
        pass
    mat.node_tree.nodes.clear()
    return mat

def emission(name, color, strength=1.0):
    mat = new_material(name)
    mat.diffuse_color = tuple(color) + (1,)
    nodes = mat.node_tree.nodes
    em = nodes.new('ShaderNodeEmission')
    em.inputs['Color'].default_value = tuple(color) + (1,)
    em.inputs['Strength'].default_value = strength
    out = nodes.new('ShaderNodeOutputMaterial')
    mat.node_tree.links.new(em.outputs['Emission'], out.inputs['Surface'])
    return mat

GOLD = emission('pole / gold', (.96, .75, .38), 1.3)
# Ground emission measured in Blender 5.2.3 (Standard, Medium High Contrast) to render as #080d12, the house graphite.
GROUND = emission('flat graphite field', (.00399, .0065, .0098), 1.0)

DOTS = new_material('dots / white to cyan')
nodes = DOTS.node_tree.nodes
at = nodes.new('ShaderNodeAttribute')
at.attribute_type = 'GEOMETRY'
at.attribute_name = 'dot_colour'
em = nodes.new('ShaderNodeEmission')
em.inputs['Strength'].default_value = 1.0
out = nodes.new('ShaderNodeOutputMaterial')
DOTS.node_tree.links.new(at.outputs['Color'], em.inputs['Color'])
DOTS.node_tree.links.new(em.outputs['Emission'], out.inputs['Surface'])

verts, faces, colours = [], [], []
for k in KEYS:
    p, r = P[k], R[k]
    segs = max(8, min(256, int(2 * math.pi * (r / PX) / 2.0)))
    base = len(verts)
    for s in range(segs):
        th = 2 * math.pi * s / segs
        verts.append((p.real + r * math.cos(th), p.imag + r * math.sin(th), 0.0))
    faces.append(tuple(range(base, base + segs)))
    colours.extend([dot_colour(k) + (1.0,)] * segs)
me = bpy.data.meshes.new('dots')
me.from_pydata(verts, [], faces)
me.update()
ca = me.color_attributes.new(name='dot_colour', type='FLOAT_COLOR', domain='POINT')
ca.data.foreach_set('color', [x for cc in colours for x in cc])
me.materials.append(DOTS)
C_ROW.objects.link(bpy.data.objects.new('dots', me))
assert len(me.polygons) == len(KEYS)
print('DOTS', len(me.polygons), 'discs', len(verts), 'vertices', flush=True)

pv, pf = [], []
for q in POLES:
    base = len(pv)
    for dx, dy in ((POLE_D, 0), (0, POLE_D), (-POLE_D, 0), (0, -POLE_D)):
        pv.append((q.real + dx, q.imag + dy, 0.001))
    pf.append((base, base + 1, base + 2, base + 3))
pm = bpy.data.meshes.new('poles / -1 and +1')
pm.from_pydata(pv, [], pf)
pm.update()
pm.materials.append(GOLD)
C_POLES.objects.link(bpy.data.objects.new('poles / -1 and +1', pm))

gm = bpy.data.meshes.new('Backdrop / graphite')
S_ = 100.0
gm.from_pydata([(-S_, -S_, -.05), (S_, -S_, -.05), (S_, S_, -.05), (-S_, S_, -.05)], [], [(0, 1, 2, 3)])
gm.materials.append(GROUND)
C_STAGE.objects.link(bpy.data.objects.new('Backdrop / graphite', gm))

cam_data = bpy.data.cameras.new('Plate / orthographic')
cam_data.type = 'ORTHO'
cam_data.ortho_scale = ORTHO
cam_data.sensor_fit = 'HORIZONTAL'
cam_data.clip_start = .1
cam_data.clip_end = 200
camera = bpy.data.objects.new('Plate / orthographic', cam_data)
C_STAGE.objects.link(camera)
camera.location = (0.0, 0.0, 60.0)
camera.rotation_euler = (0.0, 0.0, 0.0)
scene.camera = camera

t0 = time.time()
bpy.ops.render.render(write_still=True)
print('RENDER_SECONDS %.1f' % (time.time() - t0), flush=True)
assert OUTPUT.is_file()
print('RENDER_COMPLETE', OUTPUT.name, WIDTH, HEIGHT, flush=True)

# The .blend is saved after the render, so nothing of it can reach the PNG. It stays in the lane.
if OPT.get('save', '1' if OUTPUT.name == '00-cover-4k.png' else '0') == '1':
    tx = bpy.data.texts.new('EVIDENCE.json')
    tx.write(json.dumps(evidence, indent=1, ensure_ascii=False))
    scene['author'] = 'lmtlssss🜐'
    scene['figure'] = 'Winding and Mirrored, cover (second frame)'
    scene['data_sha256'] = evidence['data_sha256']
    bpy.ops.wm.save_as_mainfile(filepath=str(ROOT / 'winding-cover.blend'), compress=True)
    print('BLEND winding-cover.blend', flush=True)
